// Package comfyui controls an explicitly selected self-hosted ComfyUI endpoint.
// Mutations are never retried: a lost response may represent an accepted job.
package comfyui

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"path"
	"strings"
	"time"
)

const MaxJSON = 8 << 20
const MaxImage = 64 << 20

var ErrUncertain = errors.New("ComfyUI delivery uncertain; inspect the original request, do not resubmit")

type Client struct {
	base *url.URL
	http *http.Client
}

func New(endpoint string) (*Client, error) {
	u, e := url.Parse(endpoint)
	if e != nil || u.Host == "" || (u.Scheme != "http" && u.Scheme != "https") || u.User != nil || u.RawQuery != "" || u.Fragment != "" || (u.Path != "" && u.Path != "/") {
		return nil, errors.New("expected an explicit HTTP(S) ComfyUI origin without credentials, path or query")
	}
	u.Path = ""
	return &Client{u, &http.Client{Timeout: 30 * time.Second, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}}, nil
}
func (c *Client) Endpoint() string { return c.base.String() }
func (c *Client) request(ctx context.Context, method, route string, query url.Values, body any, limit int64) ([]byte, error) {
	u := *c.base
	u.Path = route
	u.RawQuery = query.Encode()
	var payload []byte
	var e error
	if body != nil {
		payload, e = json.Marshal(body)
		if e != nil {
			return nil, e
		}
		if len(payload) > MaxJSON {
			return nil, errors.New("request exceeds limit")
		}
	}
	req, e := http.NewRequestWithContext(ctx, method, u.String(), bytes.NewReader(payload))
	if e != nil {
		return nil, e
	}
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	resp, e := c.http.Do(req)
	if e != nil {
		if method != "GET" {
			return nil, ErrUncertain
		}
		return nil, errors.New("ComfyUI unavailable")
	}
	defer resp.Body.Close()
	b, e := io.ReadAll(io.LimitReader(resp.Body, limit+1))
	if e != nil || int64(len(b)) > limit {
		if method != "GET" {
			return nil, ErrUncertain
		}
		return nil, errors.New("invalid or oversized ComfyUI response")
	}
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		// Only prompt validation's 400 guarantees no enqueue. Other failures may
		// be generated by an intermediary after the service accepted the mutation.
		if method != "GET" && !(route == "/prompt" && resp.StatusCode == 400) {
			return nil, ErrUncertain
		}
		return nil, fmt.Errorf("ComfyUI HTTP %d (response body omitted)", resp.StatusCode)
	}
	return b, nil
}
func (c *Client) Read(ctx context.Context, kind string) (json.RawMessage, error) {
	routes := map[string]string{"info": "/system_stats", "queue": "/queue", "nodes": "/object_info"}
	route, ok := routes[kind]
	if !ok {
		return nil, errors.New("unsupported inspection")
	}
	b, e := c.request(ctx, "GET", route, nil, nil, MaxJSON)
	if e == nil && !json.Valid(b) {
		e = errors.New("invalid ComfyUI JSON")
	}
	return b, e
}

type Node struct {
	ClassType string         `json:"class_type"`
	Inputs    map[string]any `json:"inputs"`
}
type Workflow map[string]Node

func ParseWorkflow(b []byte) (Workflow, error) {
	if len(b) > MaxJSON {
		return nil, errors.New("workflow exceeds limit")
	}
	var w Workflow
	if e := json.Unmarshal(b, &w); e != nil {
		return nil, errors.New("expected API-format workflow object")
	}
	if len(w) == 0 || len(w) > 4096 {
		return nil, errors.New("workflow must have 1..4096 nodes")
	}
	for id, n := range w {
		if id == "" || n.ClassType == "" || n.Inputs == nil {
			return nil, errors.New("workflow nodes require class_type and inputs; export API format")
		}
	}
	return w, nil
}

type Submission struct {
	PromptID string  `json:"prompt_id"`
	Number   float64 `json:"number"`
}

func (c *Client) Submit(ctx context.Context, w Workflow, clientID string) (Submission, error) {
	var s Submission
	b, e := c.request(ctx, "POST", "/prompt", nil, map[string]any{"prompt": w, "client_id": clientID}, MaxJSON)
	if e != nil {
		return s, e
	}
	if json.Unmarshal(b, &s) != nil || !validID(s.PromptID) {
		return s, ErrUncertain
	}
	return s, nil
}
func validID(id string) bool {
	if id == "" || len(id) > 128 {
		return false
	}
	for _, r := range id {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '-' || r == '_') {
			return false
		}
	}
	return true
}

type Image struct {
	Filename  string `json:"filename"`
	Subfolder string `json:"subfolder"`
	Type      string `json:"type"`
}
type Output struct {
	Images []Image `json:"images"`
}
type Status struct {
	StatusStr string `json:"status_str"`
	Completed bool   `json:"completed"`
}
type History struct {
	Outputs map[string]Output `json:"outputs"`
	Status  Status            `json:"status"`
}

func (c *Client) History(ctx context.Context, id string) (*History, error) {
	if !validID(id) {
		return nil, errors.New("invalid prompt ID")
	}
	b, e := c.request(ctx, "GET", "/history/"+id, nil, nil, MaxJSON)
	if e != nil {
		return nil, e
	}
	var h map[string]History
	if json.Unmarshal(b, &h) != nil {
		return nil, errors.New("invalid history JSON")
	}
	v, ok := h[id]
	if !ok {
		return nil, nil
	}
	return &v, nil
}
func (c *Client) Wait(ctx context.Context, id string, interval time.Duration) (*History, error) {
	if interval < 100*time.Millisecond {
		return nil, errors.New("poll interval too short")
	}
	for {
		h, e := c.History(ctx, id)
		if e != nil {
			return nil, e
		}
		if h != nil && (h.Status.Completed || h.Status.StatusStr == "error") {
			if h.Status.StatusStr != "success" {
				return h, errors.New("ComfyUI execution failed")
			}
			return h, nil
		}
		t := time.NewTimer(interval)
		select {
		case <-ctx.Done():
			t.Stop()
			return nil, ctx.Err()
		case <-t.C:
		}
	}
}

// DeletePending affects only this ID; no global interrupt/clear is exposed.
// ComfyUI deletes pending entries atomically; a racing running job is untouched.
func (c *Client) DeletePending(ctx context.Context, id string) error {
	if !validID(id) {
		return errors.New("invalid prompt ID")
	}
	_, e := c.request(ctx, "POST", "/queue", nil, map[string]any{"delete": []string{id}}, MaxJSON)
	return e
}
func (c *Client) Image(ctx context.Context, i Image) ([]byte, error) {
	if i.Filename == "" || strings.ContainsAny(i.Filename, "/\\") || i.Filename == "." || i.Filename == ".." || strings.Contains(i.Subfolder, "\\") || strings.HasPrefix(i.Subfolder, "/") || (i.Subfolder != "" && (path.Clean(i.Subfolder) != i.Subfolder || i.Subfolder == ".." || strings.HasPrefix(i.Subfolder, "../"))) || i.Type != "output" {
		return nil, errors.New("invalid output image reference")
	}
	return c.request(ctx, "GET", "/view", url.Values{"filename": {i.Filename}, "subfolder": {i.Subfolder}, "type": {i.Type}}, nil, MaxImage)
}

// NodeInfo discovers one installed node schema without exporting the entire
// catalogue into a model context.
func (c *Client) NodeInfo(ctx context.Context, name string) (json.RawMessage, error) {
	if !validID(name) {
		return nil, errors.New("invalid node class")
	}
	b, e := c.request(ctx, "GET", "/object_info/"+name, nil, nil, MaxJSON)
	if e == nil && !json.Valid(b) {
		e = errors.New("invalid node JSON")
	}
	return b, e
}
